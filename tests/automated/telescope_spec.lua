local t = require("test.testutil")
local sut = require("tests.sut")
local describe, it, eq = t.describe, t.it, t.eq
local n = require("test.functional.testnvim")()
local exec_lua = n.exec_lua

sut.setup()

describe("telescope", function()
  describe("Picker", function()
    describe("attach_mappings", function()
      it("should allow for passing in a function", function()
        eq(
          1,
          exec_lua(function()
            local p = require("telescope.pickers").new({ finder = true }, {
              attach_mappings = function()
                return 1
              end,
            })
            return p.attach_mappings()
          end)
        )
      end)

      it("should override an attach mappings passed in by opts", function()
        eq(
          { "default", "opts" },
          exec_lua(function()
            local called_order = {}
            local p = require("telescope.pickers").new({
              finder = true,
              attach_mappings = function()
                table.insert(called_order, "opts")
              end,
            }, {
              attach_mappings = function()
                table.insert(called_order, "default")
              end,
            })

            p.attach_mappings()

            return called_order
          end)
        )
      end)
    end)
  end)

  describe("Sorters", function()
    describe("generic_fuzzy_sorter", function()
      it("sort matches well", function()
        exec_lua(function()
          local assert = require("test.assert")
          local sorter = require("telescope.sorters").get_generic_fuzzy_sorter()

          local exact_match = sorter:score("hello", { ordinal = "hello" })
          local no_match = sorter:score("abcdef", { ordinal = "ghijkl" })
          local ok_match = sorter:score("abcdef", { ordinal = "ab" })

          assert(exact_match < no_match, "exact match better than no match")
          assert(exact_match < ok_match, "exact match better than ok match")
          assert(ok_match < no_match, "ok match better than no match")
        end)
      end)
    end)

    describe("fuzzy_file", function()
      it("sort matches well", function()
        exec_lua(function()
          local assert = require("test.assert")
          local sorter = require("telescope.sorters").get_fuzzy_file()

          local exact_match = sorter:score("abcdef", { ordinal = "abcdef" })
          local no_match = sorter:score("abcdef", { ordinal = "ghijkl" })
          local ok_match = sorter:score("abcdef", { ordinal = "ab" })

          assert(
            exact_match < no_match,
            string.format("Exact match better than no match: %s %s", exact_match, no_match)
          )
          assert(
            exact_match < ok_match,
            string.format("Exact match better than OK match: %s %s", exact_match, ok_match)
          )
          assert(ok_match < no_match, "OK match better than no match")
        end)
      end)

      it("sorts matches after last os sep better", function()
        exec_lua(function()
          local assert = require("test.assert")
          local sorter = require("telescope.sorters").get_fuzzy_file()

          local better_match = sorter:score("aaa", { ordinal = "bbb/aaa" })
          local worse_match = sorter:score("aaa", { ordinal = "aaa/bbb" })

          assert(better_match < worse_match, "Final match should be stronger")
        end)
      end)

      it("sorts multiple finds better", function()
        exec_lua(function()
          local assert = require("test.assert")
          local sorter = require("telescope.sorters").get_fuzzy_file()

          local multi_match = sorter:score("generics", { ordinal = "exercises/generics/generics2.rs" })
          local one_match = sorter:score("generics", { ordinal = "exercises/generics/README.md" })

          assert(multi_match < one_match)
        end)
      end)
    end)

    describe("fzy", function()
      local function score(prompt, line)
        return exec_lua(function()
          local sorter = require("telescope.sorters").get_fzy_sorter()
          return sorter:score(prompt, { ordinal = line }, function(val)
            return val
          end, function()
            return -1
          end)
        end)
      end

      describe("matches", function()
        it("exact matches", function()
          t.ok(score("a", "a") >= 0)
          t.ok(score("a.bb", "a.bb") >= 0)
        end)
        it("ignore case", function()
          t.ok(score("AbB", "abb") >= 0)
          t.ok(score("abb", "ABB") >= 0)
        end)
        it("partial matches", function()
          t.ok(score("a", "ab") >= 0)
          t.ok(score("a", "ba") >= 0)
          t.ok(score("aba", "baabbaab") >= 0)
        end)
        it("with delimiters between", function()
          t.ok(score("abc", "a|b|c") >= 0)
        end)
        it("with empty query", function()
          t.ok(score("", "") >= 0)
          t.ok(score("", "a") >= 0)
        end)
        it("rejects non-matches", function()
          t.ok(score("a", "") < 0)
          t.ok(score("a", "b") < 0)
          t.ok(score("aa", "a") < 0)
          t.ok(score("ba", "a") < 0)
          t.ok(score("ab", "a") < 0)
        end)
        it("non-ASCII characters", function()
          t.ok(score("ä", "Bär") >= 0)
          t.ok(score("bär", "Bär") >= 0) -- ASCII case still ignored
          t.ok(score("カナ", "ひらがなカタカナ") >= 0)
        end)
        it("rejects bytes of a character matched across characters", function()
          t.ok(score("é", "ö©") < 0) -- C3 A9 vs C3 B6 C2 A9
          t.ok(score("あ", "いア") < 0) -- E3 81 82 vs E3 81 84 E3 82 A2
        end)
      end)

      describe("scoring", function()
        it("prefers beginnings of words", function()
          t.ok(score("amor", "app/models/order") < score("amor", "app/models/zrder"))
        end)
        it("prefers consecutive letters", function()
          t.ok(score("amo", "app/models/foo") < score("amo", "app/m/foo"))
          t.ok(score("erf", "perfect") < score("erf", "terrific"))
        end)
        it("prefers contiguous over letter following period", function()
          t.ok(score("gemfil", "Gemfile") < score("gemfil", "Gemfile.lock"))
        end)
        it("prefers shorter matches", function()
          t.ok(score("abce", "abcdef") < score("abce", "abc de"))
          t.ok(score("abc", "    a b c ") < score("abc", " a  b  c "))
          t.ok(score("abc", " a b c    ") < score("abc", " a  b  c "))
        end)
        it("prefers shorter candidates", function()
          t.ok(score("test", "tests") < score("test", "testing"))
        end)
        it("prefers matches at the beginning", function()
          t.ok(score("ab", "abbb") < score("ab", "babb"))
          t.ok(score("test", "testing") < score("test", "/testing"))
        end)
        it("prefers starts of words after any non-alphanumeric character", function()
          t.ok(score("abc", "ant!bat!cat") < score("abc", "azzzbzzzczz"))
          t.ok(score("al", "α \\alpha") < score("al", "𝚨 \\bfAlpha"))
        end)
        it("counts characters, not bytes", function()
          eq(score("ab", "axb"), score("ab", "aがb"))
          eq(score("bar", "Bar.txt"), score("bär", "Bär.txt"))
        end)
        it("prefers matches at some locations", function()
          t.ok(score("a", "/a") < score("a", "ba"))
          t.ok(score("a", "bA") < score("a", "ba"))
          t.ok(score("a", ".a") < score("a", "ba"))
        end)
      end)

      describe("case_mode", function()
        local function score_with(case_mode, prompt, line)
          return exec_lua(function()
            return require("telescope.sorters")
              .get_fzy_sorter({ case_mode = case_mode })
              :score(prompt, { ordinal = line }, function(val)
                return val
              end, function()
                return -1
              end)
          end)
        end
        it("ignores case by default", function()
          t.ok(score_with(nil, "al", "\\bfAlpha") >= 0)
          t.ok(score_with("ignore_case", "Al", "\\alpha") >= 0)
        end)
        it("respects case with respect_case", function()
          t.ok(score_with("respect_case", "al", "\\bfAlpha") < 0)
          t.ok(score_with("respect_case", "al", "\\alpha") >= 0)
          t.ok(score_with("respect_case", "Al", "\\bfAlpha") >= 0)
        end)
        it("respects case with smart_case only for prompts with uppercase", function()
          t.ok(score_with("smart_case", "al", "\\bfAlpha") >= 0)
          t.ok(score_with("smart_case", "Al", "\\alpha") < 0)
          t.ok(score_with("smart_case", "Al", "\\bfAlpha") >= 0)
        end)
        it("highlights with the same case_mode", function()
          exec_lua(function()
            local assert = require("test.assert")
            local sorters = require("telescope.sorters")
            assert.eq({ 1, 2 }, sorters.get_fzy_sorter():highlighter("ab", "aBab"))
            assert.eq({ 3, 4 }, sorters.get_fzy_sorter({ case_mode = "respect_case" }):highlighter("ab", "aBab"))
          end)
        end)
      end)

      local function positions(prompt, line)
        return exec_lua(function()
          return require("telescope.sorters").get_fzy_sorter():highlighter(prompt, line)
        end)
      end

      describe("positioning", function()
        it("favors consecutive positions", function()
          eq({ 1, 5, 6 }, positions("amo", "app/models/foo"))
        end)
        it("favors word beginnings", function()
          eq({ 1, 5, 12, 13 }, positions("amor", "app/models/order"))
        end)
        it("works when there are no bonuses", function()
          eq({ 2, 4 }, positions("as", "tags"))
          eq({ 3, 8 }, positions("as", "examples.txt"))
        end)
        it("favors smaller groupings of positions", function()
          eq({ 3, 5, 7 }, positions("abc", "a/a/b/c/c"))
          eq({ 3, 5 }, positions("ab", "caacbbc"))
        end)
        it("handles exact matches", function()
          eq({ 1, 2, 3 }, positions("foo", "foo"))
        end)
        it("returns all bytes of matched multi-byte characters", function()
          eq({ 1, 2, 3, 10, 11, 12 }, positions("かな", "かたかな"))
        end)
        it("ignores empty requests", function()
          eq({}, positions("", ""))
          eq({}, positions("", "foo"))
          eq({}, positions("foo", ""))
        end)
        it("returns no positions without a match", function()
          eq({}, positions("foo", "bar"))
        end)
      end)
    end)
  end)
end)
